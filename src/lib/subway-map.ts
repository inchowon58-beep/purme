export function getNearbyStationNames(region: string | null, count = 5): string[] {
  if (!region) return [];
  const key = normalizeCityKey(region);
  const direct = SUBWAY_MAP[key];
  if (direct?.length) return direct.slice(0, count);
  for (const [mapKey, stations] of Object.entries(SUBWAY_MAP)) {
    if (key.startsWith(mapKey) || mapKey.startsWith(key)) {
      return stations.slice(0, count);
    }
  }
  return [];
}
